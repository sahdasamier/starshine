export type MessageKey = keyof (typeof messages)['en']

interface I18nValue {
  language: Language
  t: (key: MessageKey) => string
  toggleLanguage: () => Promise<void>
}

const I18nContext = createContext<I18nValue | null>(null)

export function I18nProvider({ children }: { children: ReactNode }) {
  const { user, profile } = useAuth()
  const [localLanguage, setLocalLanguage] = useState<Language>(() => (localStorage.getItem('starshine.lang') === 'en' ? 'en' : 'ar'))
  const language = profile?.language ?? localLanguage

  useEffect(() => {
    document.documentElement.lang = language
    document.documentElement.dir = language === 'ar' ? 'rtl' : 'ltr'
    localStorage.setItem('starshine.lang', language)
  }, [language])

  const value = useMemo<I18nValue>(() => {
    return {
      language,
      t: (key) => messages[language][key] ?? messages.en[key] ?? key,
      toggleLanguage: async () => {
        const next: Language = language === 'ar' ? 'en' : 'ar'
        setLocalLanguage(next)
        if (user && profile) await updateDoc(doc(db, 'users', user.uid), { language: next })
      },
    }
  }, [language, profile, user])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  const value = useContext(I18nContext)
  if (!value) throw new Error('i18n')
  return value
}
